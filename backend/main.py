# ── File actions ───────────────────────────────────────────────────────────────
class PathRequest(BaseModel):
    path: str
    is_folder: bool = False  # True when path is itself a folder (not a file inside one)


@app.post("/api/open-folder")
async def api_open_folder(req: PathRequest):
    """Open in Windows Explorer — uses Task Scheduler to escape process sandbox."""
    import ctypes, uuid, threading

    path   = req.path
    # If is_folder, the path itself is the directory — open it directly
    if req.is_folder:
        target = path
    else:
        target = path
        if not os.path.exists(target):
            target = os.path.dirname(path)
    if not os.path.exists(target):
        raise HTTPException(404, f"Path not found: {path}")

    opened = False

    # ── Attempt 1: Task Scheduler /it (Interactive Task) ─────────────────────
    # /it means "only run when the user is interactively logged on"
    # Task Scheduler spawns the process directly in the user's live desktop,
    # bypassing any Job Object sandbox the parent process is in.
    try:
        task_name = f"OrionExplorer_{uuid.uuid4().hex[:8]}"
        if os.path.isfile(target):
            tr = f'explorer.exe /select,"{target}"'
        else:
            tr = f'explorer.exe "{target}"'

        create = subprocess.run([
            'schtasks', '/create', '/f',
            '/tn', task_name,
            '/tr', tr,
            '/sc', 'once',
            '/st', '00:00',
            '/it',          # interactive — runs on user's active desktop
        ], capture_output=True, text=True, timeout=8)

        if create.returncode == 0:
            subprocess.run(['schtasks', '/run', '/tn', task_name],
                           capture_output=True, timeout=5)
            # Clean up the task 3 s later (non-blocking)
            def _cleanup():
                import time; time.sleep(3)
                subprocess.run(['schtasks', '/delete', '/tn', task_name, '/f'],
                               capture_output=True)
            threading.Thread(target=_cleanup, daemon=True).start()
            opened = True
    except Exception:
        pass

    # ── Attempt 2: SHOpenFolderAndSelectItems ────────────────────────────────
    if not opened:
        try:
            shell32 = ctypes.windll.shell32
            ctypes.windll.ole32.CoInitialize(None)
            pidl = shell32.ILCreateFromPathW(target)
            if pidl:
                shell32.SHOpenFolderAndSelectItems(pidl, 0, None, 0)
                shell32.ILFree(pidl)
                opened = True
            ctypes.windll.ole32.CoUninitialize()
        except Exception:
            pass

    # ── Attempt 3: os.startfile on parent folder (always works) ──────────────
    if not opened:
        folder = os.path.dirname(target) if os.path.isfile(target) else target
        os.startfile(folder)

    return {"message": "Opened", "path": target}


@app.post("/api/open-file")
async def api_open_file(req: PathRequest):
    """Open the file with its default application."""
    if not os.path.exists(req.path):
        raise HTTPException(404, "File not found")
    try:
        os.startfile(req.path)
        return {"message": "Opened"}
    except Exception as e:
        raise HTTPException(500, str(e))


@app.post("/api/copy-path")
async def api_copy_path(req: PathRequest):
    """Copy the file path to Windows clipboard."""
    try:
        subprocess.run(
            ["powershell", "-command", f"Set-Clipboard -Value '{req.path}'"],
            check=True, capture_output=True
        )
        return {"message": "Copied to clipboard"}
    except Exception as e:
        raise HTTPException(500, str(e))


