# ── File metadata (preview panel) ─────────────────────────────────────────────
@app.get("/api/meta")
async def api_meta(path: str = Query(...)):
    """Return rich metadata for a single file (for preview panel)."""
    if not os.path.isfile(path):
        raise HTTPException(404, "File not found")

    from config import get_file_type
    from pathlib import Path as Pth

    ext       = Pth(path).suffix.lower().lstrip(".")
    file_type = get_file_type(ext)
    meta      = {"path": path, "file_type": file_type, "extension": ext}

    if file_type == "image":
        meta.update(get_image_meta(path))
        meta["thumbnail"] = get_thumbnail_b64(path)
    elif file_type == "audio":
        meta.update(get_audio_meta(path))
    elif file_type == "video":
        meta.update(get_video_meta(path))

    return meta


