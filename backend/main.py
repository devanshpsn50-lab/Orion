def _copy_icon():
    """Copy generated icon to assets folder."""
    assets = cfg.ASSETS_DIR
    assets.mkdir(exist_ok=True)
    # Icon was generated by AI and saved to artifacts dir — user should copy it
    # or we create a simple placeholder
    icon_dest = assets / "orion_icon.png"
    if not icon_dest.exists():
        try:
            from PIL import Image, ImageDraw
            img  = Image.new("RGB", (256, 256), color=(10, 10, 15))
            draw = ImageDraw.Draw(img)
            draw.ellipse([30, 30, 180, 180], outline=(124, 58, 237), width=8)
            draw.line([160, 160, 220, 220], fill=(124, 58, 237), width=8)
            img.save(str(icon_dest))
        except Exception:
            pass


